_Locale = ZH  # default to Chinese
_KEY_ORDER = list(EN.keys())  # so new keys surface when both tables get updated


def set_language(lang: str) -> None:
    """Pick the locale table."""
    global _Locale
    if lang in ("en", "english"):
        _Locale = EN
    else:
        _Locale = ZH


def _(key: str, *args) -> str:
    """Look up `key` in the current locale.

    If extra positional args are given, %-interpolate the first string in the value with them.
    This lets call sites write _loc._("banner.install", __version__, "  (dry run)") directly.
    """
    s = _Locale[key]
    if args:
        s = s % args
    return s
